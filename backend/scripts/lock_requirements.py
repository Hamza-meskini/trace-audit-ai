"""Write ``requirements.lock``: exact pins for the app's full dependency closure.

Run with the interpreter whose environment you have tested (no network):

    backend/venv/Scripts/python.exe backend/scripts/lock_requirements.py

The closure starts from the top-level entries of ``requirements.txt`` and
follows ``Requires-Dist`` metadata of the *installed* distributions, so the
lock records exactly what was tested -- nothing is upgraded. Markers are
evaluated for the Linux deployment target (Databricks Apps, CI) as well as the
local platform; a dependency needed on only one of them keeps its marker.

Install with:  pip install -r requirements.txt -c requirements.lock

Limitations: no ``--hash`` entries (computing them needs the package index).
Dependencies required only on the other platform and absent from this
environment (e.g. uvloop/gunicorn when locking from Windows) are listed as
comments and stay unpinned. Pins whose ``Requires-Python`` excludes the target
Python are reported on stderr.
"""

from __future__ import annotations

import argparse
import sys
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.specifiers import SpecifierSet
from packaging.utils import canonicalize_name

REPO = Path(__file__).resolve().parents[2]

LINUX_ENV = {
    "sys_platform": "linux",
    "platform_system": "Linux",
    "os_name": "posix",
    "platform_machine": "x86_64",
}
WINDOWS_ENV = {
    "sys_platform": "win32",
    "platform_system": "Windows",
    "os_name": "nt",
    "platform_machine": "AMD64",
}


def _top_level(path: Path) -> list[Requirement]:
    reqs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        reqs.append(Requirement(line))
    return reqs


def _env(base: dict, python_version: str, extra: str = "") -> dict:
    env = dict(default_environment())
    env.update(base)
    env["python_version"] = python_version
    env["python_full_version"] = f"{python_version}.0"
    env["extra"] = extra
    return env


def closure(top: list[Requirement], python_version: str) -> dict[str, dict]:
    """Return {canonical name: {"version", "platforms"}} for the installed closure."""
    found: dict[str, dict] = {}
    missing: set[str] = set()
    platforms = {"linux": LINUX_ENV, "win32": WINDOWS_ENV}
    queue: list[tuple[Requirement, set[str], str]] = [(req, set(platforms), "") for req in top]
    while queue:
        req, allowed, _origin = queue.pop()
        active = {
            name for name in allowed
            if req.marker is None or any(
                req.marker.evaluate(_env(platforms[name], python_version, extra))
                for extra in ("",)
            )
        }
        if not active:
            continue
        key = canonicalize_name(req.name)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            print(f"warning: {req.name} is required but not installed", file=sys.stderr)
            missing.add(req.name)
            continue
        entry = found.setdefault(key, {"name": dist.metadata["Name"], "version": dist.version,
                                       "platforms": set(), "extras": set(),
                                       "requires_python": dist.metadata.get("Requires-Python") or ""})
        new_platforms = active - entry["platforms"]
        new_extras = set(req.extras) - entry["extras"]
        if not new_platforms and not new_extras:
            continue
        entry["platforms"] |= active
        entry["extras"] |= set(req.extras)
        for raw in dist.requires or []:
            child = Requirement(raw)
            child_platforms = set()
            for name in entry["platforms"]:
                extras = [""] + sorted(entry["extras"])
                if child.marker is None or any(
                    child.marker.evaluate(_env(platforms[name], python_version, extra)) for extra in extras
                ):
                    child_platforms.add(name)
            if child_platforms:
                stripped = Requirement(str(child))
                stripped.marker = None
                queue.append((stripped, child_platforms, key))
    found["__missing__"] = {"names": sorted(missing)}
    return found


def render(found: dict[str, dict], python_version: str) -> str:
    lines = [
        "# Exact pins for the TraceAudit backend dependency closure.",
        "# Generated by backend/scripts/lock_requirements.py from the tested environment;",
        "# do not edit by hand. Install: pip install -r requirements.txt -c requirements.lock",
        f"# Target Python for marker evaluation: {python_version}",
    ]
    missing = found.pop("__missing__", {}).get("names", [])
    if missing:
        lines.append("# Not installed in the locking environment, left unpinned: " + ", ".join(missing))
    lines.append("")
    for key in sorted(found):
        entry = found[key]
        line = f"{entry['name']}=={entry['version']}"
        if entry["platforms"] == {"win32"}:
            line += ' ; sys_platform == "win32"'
        elif entry["platforms"] == {"linux"}:
            line += ' ; sys_platform != "win32"'
        lines.append(line)
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--requirements", default=str(REPO / "requirements.txt"))
    parser.add_argument("--out", default=str(REPO / "requirements.lock"))
    parser.add_argument("--python", default=f"{sys.version_info.major}.{sys.version_info.minor}",
                        help="target Python version for markers (default: this interpreter)")
    args = parser.parse_args(argv)
    found = closure(_top_level(Path(args.requirements)), args.python)
    Path(args.out).write_text(render(found, args.python), encoding="utf-8", newline="\n")
    found.pop("__missing__", None)
    incompatible = [
        f"{e['name']}=={e['version']} requires Python {e['requires_python']}"
        for e in found.values()
        if e["requires_python"] and args.python + ".0" not in SpecifierSet(e["requires_python"])
    ]
    for item in incompatible:
        print(f"warning: {item}", file=sys.stderr)
    print(f"wrote {len(found)} pins to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
